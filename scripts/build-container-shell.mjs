/**
 * Bundle the shell as a single Node program for the container to run.
 *
 * The interpreter, coreutils, awk, and git in `src/shell/` are written against
 * the page's virtual filesystem. Nothing about the *language* is browser-bound
 * — only the storage is — so this builds the same sources with two modules
 * swapped: `vfs/volume.ts` becomes the `node:fs`-backed twin, and `node/fs.ts`
 * becomes real `node:fs` for the git engine. The result runs inside the
 * container against the container's own files.
 *
 * Emitted into `src/generated/` as a string so the app can write it into the
 * container at boot, which keeps it a build artifact rather than a fetched one:
 * a shell arriving over the network could fail to arrive, and the agent's only
 * way to run a command would go with it.
 */

import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Redirect the page's storage modules to the container's.
 *
 * An alias would be simpler, but these are relative specifiers — every importer
 * spells `../vfs/volume.ts` from its own directory — so the resolution has to
 * happen on the resolved path rather than on the text.
 */
const swapStorage = {
  name: 'swap-storage',
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /volume\.ts$/ }, (args) => {
      if (!args.path.includes('vfs/')) return null
      return { path: resolve(root, 'src/shell/node-volume.ts') }
    })
    // The git engine wants a Node filesystem; inside the container it can have
    // the real one instead of the page's shim over the virtual volume.
    pluginBuild.onResolve({ filter: /node\/fs\.ts$/ }, () => ({ path: 'node:fs', external: true }))
  },
}

const result = await build({
  entryPoints: [resolve(root, 'src/shell/container-cli.ts')],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  // Node 22 is what the container runs, so nothing needs downlevelling; the
  // bundle is written into a filesystem the user's browser holds, and a smaller
  // one is a faster boot.
  minify: true,
  legalComments: 'none',
  plugins: [swapStorage],
  write: false,
})

const [output] = result.outputFiles
const generated = resolve(root, 'src/generated')
mkdirSync(generated, { recursive: true })
writeFileSync(resolve(generated, 'container-shell.ts'), [
  '/**',
  ' * The shell program the container runs, as source text.',
  ' *',
  ' * Generated by `scripts/build-container-shell.mjs`; do not edit. The app',
  ' * writes this into the container at boot so the agent has a real shell.',
  ' */',
  '',
  `export const CONTAINER_SHELL = ${JSON.stringify(output.text)}`,
  '',
].join('\n'))

console.log(`container shell: ${String(Math.round(output.text.length / 1024))} kB`)

/**
 * Bundle the two runtimes that live in a frame, into strings the app injects.
 *
 * `src/browser/frame.ts` runs inside a sandboxed frame with an opaque origin,
 * which is a place nothing can be *fetched* into: the frame has no network of
 * its own, and a `blob:` URL script would taint every canvas drawn afterwards.
 * So it has to arrive as part of the document, and a document is a string.
 *
 * The same shape `scripts/build-container-shell.mjs` uses, and for the same
 * reason: emitted into `src/generated/` as a build artifact rather than
 * fetched at run time, because a runtime that failed to arrive would leave a
 * browsed page with no storage, no cookies and no way to be driven — and it
 * would fail silently, one page at a time.
 *
 * The second runtime is the task realm (`src/browser/realm.ts`), which is not
 * a browsed page at all: it is the sandbox a task space's own code runs in,
 * and it is built the same way for the same reason — it lives in an opaque
 * origin, so nothing can be fetched into it either.
 */

import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Bundle one entry point into a string that can be written into a document.
 * @param {string} entry - the module to build, relative to the repository root.
 * @returns {Promise<string>} the bundle, safe to put inside a `<script>`.
 */
async function bundle(entry) {
  const result = await build({
    entryPoints: [resolve(root, entry)],
    bundle: true,
    platform: 'browser',
    // What the page itself targets. The frame is the same browser as the tab
    // around it, so there is nothing to downlevel for.
    target: 'es2022',
    format: 'iife',
    minify: true,
    legalComments: 'none',
    write: false,
  })
  const [output] = result.outputFiles
  if (output === undefined) throw new Error(`esbuild produced no output for ${entry}`)
  // `</script>` inside the bundle would close the tag it is injected into, and
  // the string is written into a document rather than into a module. Escaping
  // it here keeps every injection site from having to remember.
  return output.text.replace(/<\/script/gi, '<\\/script')
}

const generated = resolve(root, 'src/generated')
mkdirSync(generated, { recursive: true })

/** The two runtimes, each with the name it is emitted under and why it exists. */
const runtimes = [
  {
    entry: 'src/browser/frame.ts',
    file: 'browser-frame.ts',
    constant: 'BROWSER_FRAME',
    label: 'browser frame runtime',
    doc: [
      ' * The runtime every browsed page carries, as source text.',
      ' *',
      ' * Generated by `scripts/build-browser-frame.mjs`; do not edit. The engine',
      ' * writes this into the top of each document it hands a tab, ahead of',
      ' * anything the site brought with it.',
    ],
  },
  {
    entry: 'src/browser/realm.ts',
    file: 'browser-realm.ts',
    constant: 'BROWSER_REALM',
    label: 'browser task realm',
    doc: [
      ' * The runtime a task space evaluates its code in, as source text.',
      ' *',
      ' * Generated by `scripts/build-browser-frame.mjs`; do not edit. A task space',
      ' * writes this into a sandboxed frame of its own — an opaque origin, so the',
      ' * code a model writes cannot reach this page, its storage or its keys.',
    ],
  },
]

// Together, not one after the other: the two bundles share no input and write
// different files, so waiting for the first is the second's build time added
// to every `npm run build` and every CI run for nothing.
await Promise.all(runtimes.map(async (runtime) => {
  const source = await bundle(runtime.entry)
  writeFileSync(resolve(generated, runtime.file), [
    '/**',
    ...runtime.doc,
    ' */',
    '',
    `export const ${runtime.constant} = ${JSON.stringify(source)}`,
    '',
  ].join('\n'))
  console.log(`${runtime.label}: ${String(Math.round(source.length / 1024))} kB`)
}))
